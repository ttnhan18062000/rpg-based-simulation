def test_the_config_lists_exactly_the_two_local_system_hooks():
    config = yaml.safe_load((_REPO / ".pre-commit-config.yaml").read_text())
    assert config["minimum_prek_version"] == "0.5.4"
    (local,) = config["repos"]
    assert local["repo"] == "local"
    hooks = {h["id"]: h for h in local["hooks"]}
    assert set(hooks) == {"code-health-ratchet", "uv-lock-check"}
    assert all(h["language"] == "system" for h in hooks.values()), "no environment build, no network"
    assert hooks["code-health-ratchet"]["files"] == r"^src/.*\.py$"
    assert all(h["verbose"] is True for h in hooks.values()), "a skip line from a passing hook must stay visible"
    assert hooks["uv-lock-check"]["files"] == r"^(pyproject\.toml|uv\.lock)$" and hooks["uv-lock-check"]["pass_filenames"] is False
    assert "uv lock --check --offline" in (_REPO / "tools" / "hooks" / "uv_lock_pre_commit.sh").read_text(), "a commit never waits for the network"


def test_the_makefile_targets_only_call_the_installer_and_name_the_risk():
    text = (_REPO / "Makefile").read_text()
    install = next(l for l in text.splitlines() if l.startswith("install-prek-hooks:"))
    assert "OPT-IN" in install and "EVERY worktree" in install
    assert "python3 tools/hooks/install_git_hooks.py install" in text and "python3 tools/hooks/install_git_hooks.py uninstall" in text
    assert "OVERWRITES" in next(l for l in text.splitlines() if l.startswith("install-hooks:"))


def test_nothing_installs_hooks_implicitly():
    """No other Makefile target, script, workflow or Claude Code configuration may install or depend on the hooks."""
    lines = (_REPO / "Makefile").read_text().splitlines()
    for line in lines:
        if line.startswith(("install-prek-hooks:", "uninstall-prek-hooks:", "install-hooks:", ".PHONY")) or line.startswith("\t") or ":" not in line:
            continue
        dependencies = line.split(":", 1)[1].split("##")[0]
        assert "install-prek-hooks" not in dependencies and "install-hooks" not in dependencies, line
    for name in ("install:", "install-py:"):
        assert "hooks" not in next(l for l in lines if l.startswith(name)).split("##")[0]
    needles = ("install-prek-hooks", "install_git_hooks", "prek install")
    scanned = [p for pattern in (".github/workflows/*.yml", "tools/**/*.sh", "tools/**/*.py", "make.bat", ".claude/settings*.json")
               for p in _REPO.glob(pattern)]
    def code(path: Path) -> str:  # comments may name the opt-in target; only executable lines count
        return "\n".join(l for l in path.read_text(errors="replace").splitlines() if not l.lstrip().startswith("#"))

    offenders = [p.relative_to(_REPO).as_posix() for p in scanned
                 if p.name != "install_git_hooks.py" and any(n in code(p) for n in needles)]
    assert offenders == [], offenders
    recipe_lines = [l for l in lines if l.startswith("\t") and any(n in l for n in needles)]
    assert recipe_lines == ["\tpython3 tools/hooks/install_git_hooks.py install", "\tpython3 tools/hooks/install_git_hooks.py uninstall"]
